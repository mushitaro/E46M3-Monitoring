/**
 * Which module is at an address, chosen the way EDIABAS chooses it: from the module's own answer to
 * the common DS2 IDENT (`<addr> 04 00`), by the group file's rule (`D_00xx.grp`, IDENTIFIKATION).
 *
 * ## Why this exists
 *
 * The module list is the E46 M3's. Until this, the app sent 0x12 the MSS54's frames and 0x32 the SMG
 * II's on whatever car it was plugged into, and decoded 0x12's answers as the MSS54's. On a non-M3
 * E46 (MS42/MS43, M43, GS20) that is another module's bytes sent to a DME and a gearbox, and fiction
 * read back. So the rule is now: **frames other than the common IDENT go to an address only when
 * its IDENT answer has chosen a module this app carries, and only that module's frames.**
 *
 * An address with no rule yet is `?`. On a car whose DME has identified itself as the MSS54 — an M3
 * — such an address keeps the M3 fitment the module list was built on (the frames every M3
 * candidate's table carries, lib/probe/scan); on any other car it is sent its IDENT and nothing
 * else.
 *
 * ## Where the rules come from
 *
 * `ecu-data/variants.json`, generated by tools/sgbd/gen_variants.py: which bytes each group reads and
 * in which order is written there from the group file's disassembly, the table rows are read out of
 * the group file, and the result is checked against EdiabasLib running the group file itself on
 * every table key and thousands of other answers (`variants.oracle.json`, which the tests here read
 * too). BMW-derived, so it ships with the private data; without it nothing is identified, and that
 * fails closed: no address is cleared, so only IDENTs go.
 */

import { readEcuData } from './ecuData';

/** A slice of the answer: `[start, length]` into the whole frame (address, length, status, data, checksum). */
export type Slice = readonly [number, number];

/** What a step of a rule comes to: an SGBD name, another lookup, or nothing chosen. */
export type Choice = string | Lookup | null;

export interface Lookup {
    /** The slices whose text, joined, is the key. Each stops at a NUL, as a BEST/2 string does. */
    key: readonly Slice[];
    /** Compared without regard to case; the first matching row wins. */
    rows: ReadonlyArray<readonly [string, Choice]>;
    else: Choice;
}

export interface GroupRule {
    address: number;
    /** `D_0012`: the group file the rule was read from. */
    group: string;
    groupSha256: string;
    /** The status byte of an answer the group reads on DS2's road (0xA0). Any other: nothing chosen. */
    positive: number;
    choose: Choice;
    /** Names the group returns that mean "not found" (D_0032's last row, `XYZ`), not an SGBD. */
    unknown: readonly string[];
}

export interface VariantRules {
    schema: 1;
    generatedAt: string;
    groups: readonly GroupRule[];
}

export const NO_RULES: VariantRules = { schema: 1, generatedAt: '', groups: [] };

/** The SGBD of the late E46 M3's DME. The car is an M3 when 0x12 has said it is this one. */
export const M3_DME_SGBD = 'MSS54DS0';
export const DME_ADDRESS = 0x12;

function keyOf(answer: Uint8Array, slices: readonly Slice[]): string {
    let out = '';
    for (const [start, length] of slices) {
        // Past the end of a short answer the group's substring is shorter, not an error (checked
        // against EdiabasLib with answers cut at 0–13 bytes).
        for (let i = start; i < start + length && i < answer.length; i++) {
            if (answer[i] === 0) break;
            out += String.fromCharCode(answer[i]);
        }
    }
    return out;
}

/** The group's choice for this answer, exactly as EDIABAS would return it (`XYZ` included). */
export function groupChoice(rule: GroupRule, answer: Uint8Array): string | null {
    if (answer.length < 3 || answer[0] !== rule.address || answer[2] !== rule.positive) return null;
    let choice: Choice = rule.choose;
    while (choice !== null && typeof choice !== 'string') {
        const key = keyOf(answer, choice.key).toUpperCase();
        const row: (readonly [string, Choice]) | undefined = choice.rows.find(([k]) => k.toUpperCase() === key);
        choice = row ? row[1] : choice.else;
    }
    return choice;
}

/** The SGBD this answer identifies, or null: not positive, no row, or the group's "not found". */
export function variantOf(rule: GroupRule, answer: Uint8Array): string | null {
    const v = groupChoice(rule, answer);
    return v !== null && !rule.unknown.includes(v) ? v : null;
}

export function ruleFor(rules: VariantRules, address: number): GroupRule | null {
    return rules.groups.find((g) => g.address === address) ?? null;
}

/** What one address said to its IDENT this session. */
export interface Fitted {
    address: number;
    /** The whole answer frame, hex, or null when it did not answer. */
    answer: string | null;
    /** The status byte when it answered with a refusal. */
    status?: number;
    /** The SGBD its group chose; null when no rule, no row, or no positive answer: `?`. */
    sgbd: string | null;
    /** The module this app carries for that SGBD; null when it does not carry it. */
    moduleId: string | null;
}

export type Fitment = ReadonlyMap<number, Fitted>;

/** The app's module for an SGBD file name (`MSS54DS0` ← `MSS54DS0.prg`), from the catalogue index. */
export function moduleForSgbd(modules: ReadonlyArray<{ id: string; sgbd: string }>, sgbd: string): string | null {
    const want = sgbd.toUpperCase();
    return modules.find((m) => m.sgbd.replace(/\.prg$/i, '').toUpperCase() === want)?.id ?? null;
}

/** What `answer` (a whole frame, or null for silence) says about `address`. */
export function fittedFrom(
    rules: VariantRules,
    modules: ReadonlyArray<{ id: string; sgbd: string }>,
    address: number,
    answer: Uint8Array | null,
): Fitted {
    if (!answer) return { address, answer: null, sgbd: null, moduleId: null };
    const hex = toHex(answer);
    const rule = ruleFor(rules, address);
    const status = answer.length >= 3 ? answer[2] : undefined;
    const refused = status !== undefined && status !== 0xa0 ? { status } : {};
    const sgbd = rule ? variantOf(rule, answer) : null;
    return { address, answer: hex, ...refused, sgbd, moduleId: sgbd ? moduleForSgbd(modules, sgbd) : null };
}

/** True when the DME has said it is the MSS54: the car the module list was built for. */
export function isM3(fitment: Fitment): boolean {
    return fitment.get(DME_ADDRESS)?.sgbd === M3_DME_SGBD;
}

export type ModuleVerdict =
    | { ok: true; basis: 'identified' | 'm3-fitment' }
    | { ok: false; reason: string };

/**
 * May frames built for `moduleId` (beyond the common IDENT) go to `address` now?
 *
 *   - An address with a rule: only when its IDENT chose exactly this module.
 *   - An address without one: only on a car identified as an M3 (its DME is the MSS54), where the
 *     module list's M3 fitment is what it was made for.
 *
 * Not identified yet is a refusal, not a pass: the caller identifies first (useDs2Link).
 */
export function mayModuleBeSent(address: number, moduleId: string, fitment: Fitment, rules: VariantRules): ModuleVerdict {
    const at = hex2(address);
    const f = fitment.get(address);
    if (ruleFor(rules, address)) {
        if (!f) return { ok: false, reason: `${at}: not identified yet — its IDENT is read first` };
        if (f.moduleId === moduleId) return { ok: true, basis: 'identified' };
        if (f.sgbd && !f.moduleId) return { ok: false, reason: `${at} is ${f.sgbd}, whose SGBD this app does not carry yet: only its IDENT is sent` };
        if (f.sgbd) return { ok: false, reason: `${at} is ${f.sgbd}, not ${moduleId}: ${moduleId}'s frames are not sent to it` };
        if (f.answer === null) return { ok: false, reason: `${at} did not answer its IDENT` };
        return { ok: false, reason: `${at}: its IDENT answer chose no variant (?): only its IDENT is sent` };
    }
    if (isM3(fitment)) return { ok: true, basis: 'm3-fitment' };
    const dme = fitment.get(DME_ADDRESS);
    const car = !dme ? 'the DME has not been identified' : dme.sgbd ? `the DME is ${dme.sgbd}, not the M3's ${M3_DME_SGBD}` : 'the DME did not identify itself as an M3';
    return { ok: false, reason: `${at}: which module answers here is not known (?) and ${car}: only its IDENT is sent` };
}

/** `<addr> 04 00 <cs>`: the IDENT every DS2 group file sends, and the one frame an unknown address gets. */
export function commonIdent(address: number): Uint8Array {
    return Uint8Array.from([address, 0x04, 0x00, address ^ 0x04]);
}

export function isCommonIdent(frame: Uint8Array): boolean {
    return frame.length === 4 && frame[1] === 0x04 && frame[2] === 0x00 && frame[3] === (frame[0] ^ 0x04);
}

/**
 * The link's last word before bytes go (Ds2Link `setSendGuard`): null to send, else why not. Knows
 * only the address — the module behind a frame is the caller's to check (`mayModuleBeSent`) — so it
 * is the backstop under every path, not the whole rule.
 *
 * `identOk`: the addresses whose common IDENT is their own (every candidate SGBD's table carries
 * it, or the group file sends it). Any other address is not sent even that.
 */
export function frameVerdict(frame: Uint8Array, fitment: Fitment, rules: VariantRules, identOk: ReadonlySet<number>): string | null {
    const address = frame[0];
    if (isCommonIdent(frame)) return identOk.has(address) ? null : `${hex2(address)}: the common IDENT is not this address's own; not sent`;
    const f = fitment.get(address);
    if (ruleFor(rules, address)) {
        return f?.moduleId ? null : `${hex2(address)}: not identified as a module this app carries (?): only its IDENT is sent`;
    }
    return isM3(fitment) ? null : `${hex2(address)}: the car has not identified itself as an M3, and this address has no variant rule (?): only its IDENT is sent`;
}

/**
 * The addresses the common IDENT may go to: those with a group rule (the group file sends it), and
 * those where every carried candidate's own IDENT frame is exactly it.
 */
export function identAddresses(
    protocols: ReadonlyArray<{ address: number; ident: { hex: string } | null; kwp: unknown }>,
    rules: VariantRules,
): Set<number> {
    const byAddress = new Map<number, Array<{ ident: { hex: string } | null; kwp: unknown }>>();
    for (const p of protocols) byAddress.set(p.address, [...(byAddress.get(p.address) ?? []), p]);
    const out = new Set<number>(rules.groups.map((g) => g.address));
    for (const [address, group] of byAddress) {
        const want = toHex(commonIdent(address));
        if (group.every((p) => !p.kwp && p.ident && normHex(p.ident.hex) === want)) out.add(address);
    }
    return out;
}

/** Fetched once per page; a missing file is no rules, which clears no address (fails closed). */
export async function loadVariantRules(): Promise<VariantRules> {
    try {
        const res = await readEcuData('variants.json');
        if (!res.ok) return NO_RULES;
        const data = (await res.json()) as VariantRules;
        return data?.schema === 1 && Array.isArray(data.groups) ? data : NO_RULES;
    } catch {
        return NO_RULES;
    }
}

const hex2 = (n: number) => `0x${n.toString(16).toUpperCase().padStart(2, '0')}`;
const toHex = (b: Uint8Array) => Array.from(b, (x) => x.toString(16).toUpperCase().padStart(2, '0')).join(' ');
const normHex = (s: string) => s.trim().toUpperCase().split(/\s+/).join(' ');
